#!/usr/bin/env python3
"""
Fetch symbol universes from each broker's REST API into
src/ingestion/symbols/<broker>.txt

    python scripts/fetch_symbols.py --broker dnse
    python scripts/fetch_symbols.py --broker all

Credentials are read from the same environment variables the ingestion service
uses, so if the service runs, this script runs.

NOT YET EXERCISED against real credentials — the endpoints come from the vendor
documentation (docs/*/details/). If a broker moves a path, edit the constant at
the top of the relevant function.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "src" / "ingestion" / "symbols"


def _write(name: str, symbols: list[str]) -> None:
    symbols = sorted({s.strip().upper() for s in symbols if s and s.strip()})
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / f"{name}.txt"
    path.write_text(
        f"# Generated by scripts/fetch_symbols.py — {len(symbols)} symbols\n"
        + "\n".join(symbols) + "\n",
        encoding="utf-8",
    )
    print(f"  {name}: {len(symbols)} symbols -> {path.relative_to(ROOT)}")


def fetch_ssi() -> list[str]:
    """GET /api/v3/data/securitiesByBoard for each exchange board."""
    base = os.getenv("SSI_API_URL", "https://api.ssi.com.vn")
    key, secret = os.getenv("SSI_API_KEY", ""), os.getenv("SSI_API_SECRET", "")
    if not (key and secret):
        raise SystemExit("missing SSI_API_KEY / SSI_API_SECRET")

    with httpx.Client(timeout=30.0) as c:
        tok = c.post(f"{base}/api/v3/auth/token",
                     json={"apiKey": key, "apiSecret": secret}).json()["accessToken"]
        out: list[str] = []
        for board in ("HOSE", "HNX", "UPCOM"):
            r = c.get(f"{base}/api/v3/data/securitiesByBoard",
                      params={"board": board},
                      headers={"Authorization": f"Bearer {tok}"})
            r.raise_for_status()
            body = r.json()
            rows = body.get("data") or body.get("items") or []
            out += [row.get("symbol") or row.get("Symbol") for row in rows]
    return [s for s in out if s]


def fetch_dnse() -> list[str]:
    """
    GET /instruments — DNSE signs REST requests with HTTP Signature, which is
    considerably more involved than its WebSocket auth. Until that signing is
    implemented, use a manually maintained universe.
    """
    raise SystemExit(
        "DNSE requires HTTP Signature for REST (different from its WebSocket signing).\n"
        "See docs/dnse/details/guide/intro/authentication.md, Signature section.\n"
        "For now: copy src/ingestion/symbols/vn30.txt to dnse.txt."
    )


def fetch_tcbs() -> list[str]:
    """Securities lookup — TCBS docs section 5.11."""
    base = os.getenv("TCBS_REST_URL", "https://openapi.tcbs.com.vn")
    token = os.getenv("TCBS_TOKEN", "")
    if not token:
        raise SystemExit("missing TCBS_TOKEN")
    with httpx.Client(timeout=30.0) as c:
        r = c.get(f"{base}/thesis/v1/securities",
                  headers={"Authorization": f"Bearer {token}"})
        r.raise_for_status()
        body = r.json()
    rows = body if isinstance(body, list) else body.get("data", [])
    return [row.get("symbol") for row in rows if isinstance(row, dict)]


FETCHERS = {"ssi": fetch_ssi, "dnse": fetch_dnse, "tcbs": fetch_tcbs}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--broker", required=True, choices=[*FETCHERS, "all"])
    args = ap.parse_args()

    targets = list(FETCHERS) if args.broker == "all" else [args.broker]
    rc = 0
    for name in targets:
        print(f"==> {name}")
        try:
            _write(name, FETCHERS[name]())
        except SystemExit as exc:
            print(f"  SKIPPED: {exc}", file=sys.stderr)
            rc = 1
        except Exception as exc:
            print(f"  ERROR: {exc!r}", file=sys.stderr)
            rc = 1
    return rc


if __name__ == "__main__":
    sys.exit(main())
